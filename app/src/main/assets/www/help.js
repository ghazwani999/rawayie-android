/* صندوق الشرح أعلى القسم. يظهر فقط مع زر «الشرح» (#set.showhints) */
function helpHTML(k){
  var h = HELP[k]; if (!h) return "";
  var e = function(t){ return String(t).replace(/[&<>"]/g, function(c){ return {"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;"}[c]; }); };
  return '<div class="shelp" role="note"><b class="shelp-t">عن هذا القسم</b><p>' + e(h[0]) + '</p>' +
    (h[1] && h[1].length ? '<b class="shelp-t">كيف يعمل</b><ol>' + h[1].map(function(x){ return '<li>' + e(x) + '</li>'; }).join("") + '</ol>' : "") +
    (h[2] ? '<p class="shelp-tip">' + e(h[2]) + '</p>' : "") + '</div>';
}
